    def _show_map_message(self, text: str) -> None:
        self.map_toast.setText(text)
        self.map_toast.setVisible(bool(text) and not text.startswith("就绪"))
        self._position_map_overlays()

    def _position_map_overlays(self) -> None:
        if not hasattr(self, "map_coordinates"):
            return
        width, height = self.map.width(), self.map.height()
        toolbar_width = min(self.map_toolbar.sizeHint().width(), max(100, width - 32))
        self.map_toolbar.resize(toolbar_width, self.map_toolbar.sizeHint().height())
        self.map_toolbar.move(16, 16)
        self.map_compass.adjustSize()
        self.map_compass.setVisible(width > toolbar_width + self.map_compass.width() + 48)
        self.map_compass.move(width - self.map_compass.width() - 16, 16)
        self.map_coordinates.adjustSize()
        self.map_coordinates.move(max(12, width - self.map_coordinates.width() - 16), height - self.map_coordinates.height() - 16)
        self.map_guide.adjustSize()
        guide_y = height - self.map_guide.height() - 16
        if width < self.map_guide.width() + self.map_coordinates.width() + 48:
            guide_y -= self.map_coordinates.height() + 8
        self.map_guide.move(16, guide_y)
        self.map.scale_bottom_margin = max(62, height - guide_y + 12)
        self.map_toast.setMaximumWidth(max(100, width - 32))
        self.map_toast.setWordWrap(True)
        self.map_toast.adjustSize()
        self.map_toast.move(16, self.map_toolbar.geometry().bottom() + 10)

    def eventFilter(self, watched, event):
        if watched is getattr(self, "map", None) and event.type() == QEvent.Resize:
            self._position_map_overlays()
        return super().eventFilter(watched, event)

