        self.act_use_view.setIcon(icon("select"))
        self.btn_draw.setIcon(icon("select", COLORS["primary"]))
        self.btn_locate.setIcon(icon("locate"))
        self.btn_download_start.setIcon(icon("download", COLORS["on_primary"]))
        self.btn_download_stop.setIcon(icon("stop"))
        self._download_folder_action.setIcon(icon("folder"))
        self._refresh_layer_buttons(refresh_icons=True)
        self.map.update()
        for renderer in (self._cesium, self._mars3d):
            if renderer is not None:
                renderer.set_theme()
        QTimer.singleShot(0, self._position_map_overlays)
        QTimer.singleShot(0, self._adjust_task_height)
