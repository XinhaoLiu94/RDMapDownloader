    def _on_theme_changed(self, _scheme=None) -> None:
        with QSignalBlocker(self.theme_combo):
            self.theme_combo.setCurrentIndex(self.theme_combo.findData(self._theme_manager.mode))
        for index, name in enumerate(("system", "sun", "moon")):
            self.theme_combo.setItemIcon(index, icon(name))
        self.brand_label.setPixmap(brand_pixmap())
        self.setWindowIcon(QIcon(brand_pixmap()))
