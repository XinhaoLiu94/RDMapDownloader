    def _refresh_layer_buttons(self, refresh_icons=False) -> None:
        keys = [str(self.provider_combo.itemData(i)) for i in range(self.provider_combo.count())]
        def kind(key):
            if "hybrid" in key: return "hybrid"
            if "satellite" in key: return "satellite"
            if key == "road": return "road"
            return "street"
        keys.sort(key=lambda key: (dict(hybrid=0, satellite=1, street=2, road=3)[kind(key)], key))
        if list(self._layer_buttons) != keys:
            for button in self._layer_buttons.values():
                self._layer_button_group.removeButton(button)
                self._layer_choices_layout.removeWidget(button)
                button.deleteLater()
            self._layer_buttons = {}
            for key in keys:
                provider = PROVIDER_MAP[key]
                name = {"hybrid": "卫星 + 标注", "satellite": "纯卫星", "street": "街道地图", "road": "路网标注"}[kind(key)]
                if "terrain" in key: name = "地形地图"
                button = QToolButton()
                button.setObjectName("layerButton")
                button.setText(name)
                button.setAccessibleName(provider.name)
                button.setToolTip(provider.description)
                button.setCheckable(True)
                button.setToolButtonStyle(Qt.ToolButtonTextUnderIcon)
                button.setIconSize(QSize(104, 36))
                button.setSizePolicy(QSizePolicy.Ignored, QSizePolicy.Fixed)
                button.setMinimumHeight(72)
                button.clicked.connect(lambda _checked=False, k=key: self.provider_combo.setCurrentIndex(self.provider_combo.findData(k)))
                self._layer_button_group.addButton(button)
                self._layer_choices_layout.addWidget(button, 1)
                self._layer_buttons[key] = button
            refresh_icons = True
        for key, button in self._layer_buttons.items():
            if refresh_icons: button.setIcon(layer_icon(kind(key)))
            button.setChecked(key == self.provider_combo.currentData())

